#!/usr/bin/env python3
"""Runtime-switchable code patches ("xpatch") for the lifter.

Windows mods (ASI plugins) change instructions in memory: a NOP over a branch,
a jcc turned into jmp, a new immediate, a jump into a code cave.  The lifter
turns instructions into C at generation time, so writing those bytes into guest
memory at run time does nothing.  An xpatch site is lifted TWICE instead: the
original code, and the patched version behind a run-time switch:

    if (g_xpatch[XP_<name>]) { <patched code>; goto <end of region>; }
    <original code>

The runtime (runtime/xpatch.c) owns g_xpatch[]; a feature sets it from its settings and its
hotkeys can flip a switch while the game runs.  One switch (name) may cover
several sites.

Spec file (tools/xpatch_eu.txt), one site per line, addresses in hex:

  w    <name> <addr> <hex bytes>         raw write, as the plugin would do it.
                                         The region is widened to whole
                                         original instructions; writes of one
                                         name that touch neighbouring
                                         instructions form one region.
  wv   <name> <addr> <VAR>               one byte written with a value chosen at
                                         run time: g_xpval[XPV_<VAR>] (0..127)
  c    <name> <addr> <end> <C code>      replace [addr,end) with C code.  The
                                         code may 'return;'; otherwise it
                                         continues at <end>.
  cave <name> <addr> <end> <tokens>      replace [addr,end) with x86 code that is
                                         lifted like the game's own.  Tokens:
                                         hex bytes, d32:<hex> (little-endian
                                         dword), call:<hex> (call rel32).
  # comment

A placeholder byte is lifted for 'wv' and its C constant is swapped for the
run-time value; generation stops if that constant is not unique.
"""
import os, re, sys, struct

PLACEHOLDERS = (0x5d, 0x6b, 0x71, 0x4f, 0x63, 0x3b)

class Site:
    __slots__ = ('name', 'idx', 'kind', 'a', 'e', 'data', 'var')
    def __init__(self, **k):
        for s in self.__slots__: setattr(self, s, k.get(s))

class Spec:
    def __init__(self, path):
        self.names = []; self.vars = []
        self.writes = []      # (name, addr, bytes, var or None)
        self.regions = []     # Site for c/cave
        for ln, raw in enumerate(open(path), 1):
            line = raw.strip()
            if not line or line.startswith('#'): continue
            kind, rest = line.split(None, 1)
            if kind in ('w', 'wv', 'cave'):
                rest = rest.split(' #', 1)[0]
            f = rest.split(None, 3 if kind in ('c', 'cave') else 2)
            name = f[0]
            if name not in self.names: self.names.append(name)
            idx = self.names.index(name)
            if kind == 'w':
                self.writes.append((name, int(f[1], 16), bytes.fromhex(''.join(f[2].split())), None))
            elif kind == 'wv':
                var = f[2].strip()
                if var not in self.vars: self.vars.append(var)
                self.writes.append((name, int(f[1], 16), None, var))
            elif kind == 'c':
                self.regions.append(Site(name=name, idx=idx, kind='c', a=int(f[1], 16),
                                         e=int(f[2], 16), data=f[3]))
            elif kind == 'cave':
                a = int(f[1], 16)
                self.regions.append(Site(name=name, idx=idx, kind='cave', a=a,
                                         e=int(f[2], 16), data=assemble(a, f[3].split())))
            else:
                raise SystemExit(f"{path}:{ln}: unknown kind {kind}")

    def header(self):
        out = ["/* Generated by tools/xpatch.py -- do not edit. */", "#pragma once",
               f"#define XP_COUNT {len(self.names)}", f"#define XPV_COUNT {len(self.vars)}"]
        out += [f"#define XP_{n.upper()} {i}" for i, n in enumerate(self.names)]
        out += [f"#define XPV_{v.upper()} {i}" for i, v in enumerate(self.vars)]
        out.append("static const char *const xp_names[] = { " +
                   ", ".join(f'"{n}"' for n in self.names) + (", " if self.names else "") + "0 };")
        out.append("static const char *const xpv_names[] = { " +
                   ", ".join(f'"{v}"' for v in self.vars) + (", " if self.vars else "") + "0 };")
        return "\n".join(out) + "\n"

    def sites_for(self, L, blocks):
        """{start address: Site} for the sites whose code is in this function."""
        ins = {}
        for b in blocks.values():
            for i in b: ins[i.address] = i
        if not ins: return {}
        order = sorted(ins)
        def covering(a):
            for x in order:
                i = ins[x]
                if x <= a < x + i.size: return i
            return None
        out = {}
        # raw writes: group by name into whole-instruction regions
        by_name = {}
        for name, a, data, var in self.writes:
            n = 1 if data is None else len(data)
            hit = [covering(a + k) for k in range(n)]
            if any(h is None for h in hit): continue
            by_name.setdefault(name, []).append((a, data, var, hit))
        for name, ws in by_name.items():
            insts = sorted({h.address: h for _, _, _, hs in ws for h in hs}.values(), key=lambda i: i.address)
            groups = []
            for i in insts:
                if groups and groups[-1][-1].address + groups[-1][-1].size == i.address:
                    groups[-1].append(i)
                else:
                    groups.append([i])
            for g in groups:
                a0 = g[0].address; e0 = g[-1].address + g[-1].size
                buf = bytearray(b''.join(bytes(i.bytes) for i in g))
                vars_ = []
                for a, data, var, _ in ws:
                    if not a0 <= a < e0: continue
                    if data is None:
                        vars_.append((a - a0, var))
                    else:
                        buf[a - a0:a - a0 + len(data)] = data
                out[a0] = Site(name=name, idx=self.names.index(name), kind='w', a=a0, e=e0,
                               data=bytes(buf), var=vars_)
        for s in self.regions:
            if s.a in ins and (s.e in ins or s.e in blocks or covering(s.e - 1)):
                out[s.a] = s
        return out

def assemble(a, toks):
    buf = bytearray()
    for t in toks:
        if t.startswith('call:'):
            tgt = int(t[5:], 16); here = a + len(buf)
            buf += b'\xe8' + struct.pack('<i', tgt - (here + 5))
        elif t.startswith('d32:'):
            buf += struct.pack('<I', int(t[4:], 16) & 0xffffffff)
        else:
            buf += bytes.fromhex(t)
    return bytes(buf)

def load(path):
    return Spec(path) if path else None

if __name__ == '__main__':
    # tools/xpatch.py header <spec> <out.h>
    if len(sys.argv) == 4 and sys.argv[1] == 'header':
        open(sys.argv[3], 'w').write(Spec(sys.argv[2]).header())
    else:
        print(__doc__)
