#!/bin/bash
# Binarius' script engine on macOS: installs Binary / Binarius mods (Unlimiter's data half, Detailed Map, ...).
#
#   tools/mods/binarius/build.sh        -> out/binarius/modinstall/modinstall
#
# 1. Clones nlgxzef's libraries at the commits this was tested with (MIT:
#    Endscript, Darius = Nikki, CoreExtensions; Binarius itself, GPL, only for
#    its key list Data/MainKeys/underground2.txt) into out/binarius/src.
# 2. Applies patches/*.patch (macOS: no LZCompressLib.dll, Windows paths):
#    - Nikki Interop: JDLZ and RAWW in C#, HUFF through libhuff.dylib
#    - Nikki TPKBlock: the TPK's file name in the data is a Windows path
#    - Endscript unlock_memory / speedreflect: Path.Combine instead of "\"
# 3. libhuff.dylib: the game's own HUFF decoder (SPEED2.EXE NA v1.2, 0x573840),
#    taken from the lifted engine in gen/na (so gen/na must exist: tools/gen_v2.sh).
#    Lifted code stays in out/, as gen/ does: it is derived from the exe.
# 4. dotnet build of modinstall (needs the .NET SDK, 6 or later).
# 5. a self-contained single-file copy for the app (out/binarius/modinstall-app).
set -e
ROOT="$(cd "$(dirname "$0")/../../.." && pwd)"; cd "$ROOT"
HERE=tools/mods/binarius
OUT=out/binarius
mkdir -p "$OUT/src"

clone(){  # name commit
  local d="$OUT/src/$1"
  if [ ! -d "$d/.git" ]; then git clone -q "https://github.com/nlgxzef/$1.git" "$d"; fi
  git -C "$d" fetch -q --depth 1 origin "$2" 2>/dev/null || true
  git -C "$d" checkout -q -f "$2"
}
clone Endscript      1ab163c60b46a0ae3f52732b255101a177dc652c
clone Darius         4ebed98e778aeee7a56ac903aee6954b5b4b5896
clone CoreExtensions dd4f40fbda3192160d22ea63c8fec59c52154794
clone Binarius       7145cafde781bec009f9fbae30e0c449dcfa69c9
git -C "$OUT/src/Endscript" apply "$ROOT/$HERE/patches/endscript.patch"
git -C "$OUT/src/Darius"    apply "$ROOT/$HERE/patches/darius.patch"

# libhuff: sub_00573840 out of the lifted NA engine.  It calls nothing; its only
# global, [0x8650f8], is a .bss dword nothing in the exe writes (always 0).
SH=$(grep -l "^void sub_00573840_m(CPU" gen/na/shard_*.c | head -1)
[ -n "$SH" ] || { echo "gen/na has no sub_00573840 (run tools/gen_v2.sh <NA SPEED2.EXE>)"; exit 1; }
{ echo '/* EA HUFF decoder: SPEED2.EXE (NA v1.2) sub_00573840, lifted. Generated by'
  echo "   tools/mods/binarius/build.sh from $SH: do not edit. */"
  echo '#include "cpu.h"'; echo '#define g_mem _mb'
  awk '/^void sub_00573840_m\(CPU/{p=1} p{print} p && /^}/{exit}' "$SH" \
    | sed 's#MR32(0x8650f8u)#0u /* [0x8650f8]: .bss, never written */#g'
} > "$OUT/huff_lifted.c"
clang -O2 -fno-strict-aliasing -dynamiclib -arch arm64 -mmacosx-version-min=11.0 -I runtime \
      -Wno-unused-label -Wno-parentheses-equality \
      -o "$OUT/libhuff.dylib" "$HERE/huff.c" "$OUT/huff_lifted.c"

# the runner (its project file points at out/binarius/src)
mkdir -p "$OUT/modinstall-src"
cp "$HERE/modinstall/Program.cs" "$HERE/modinstall/modinstall.csproj" "$OUT/modinstall-src/"
DOTNET_CLI_TELEMETRY_OPTOUT=1 dotnet build "$OUT/modinstall-src/modinstall.csproj" -c Release \
    -p:PlatformTarget=AnyCPU -p:BinariusSrc="$ROOT/$OUT/src" -o "$OUT/modinstall" -nologo -v q
echo "built: $OUT/modinstall/modinstall"

# 5. the app's copy (pack.sh): .NET inside, one file, so players need no .NET.
#    PlatformTarget=AnyCPU: Nikki's project file asks for x86 in Release.
APPDIR="$OUT/modinstall-app"
rm -rf "$APPDIR.tmp"
DOTNET_CLI_TELEMETRY_OPTOUT=1 dotnet publish "$OUT/modinstall-src/modinstall.csproj" -c Release -r osx-arm64 \
    --self-contained true -p:PlatformTarget=AnyCPU -p:PublishSingleFile=true -p:EnableCompressionInSingleFile=true \
    -p:DebugType=none -p:GenerateDocumentationFile=false -p:BinariusSrc="$ROOT/$OUT/src" -o "$APPDIR.tmp" -nologo -v q
rm -rf "$APPDIR"; mkdir -p "$APPDIR/LICENSES"
cp "$APPDIR.tmp/modinstall" "$OUT/libhuff.dylib" "$APPDIR/"
rm -rf "$APPDIR.tmp"
cp "$OUT/src/Endscript/LICENSE" "$APPDIR/LICENSES/Endscript.txt"
cp "$OUT/src/Darius/LICENSE" "$APPDIR/LICENSES/Darius.txt"
cp "$OUT/src/CoreExtensions/LICENSE.md" "$APPDIR/LICENSES/CoreExtensions.txt"
echo "built: $APPDIR/modinstall (for the app, .NET included)"
