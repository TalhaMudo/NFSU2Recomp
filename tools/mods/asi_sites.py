#!/usr/bin/env python3
"""Turn a plugin's recorded code patches into xpatch sites and the runtime table.

    asi_sites.py <out/ul/meta.json> <SPEED2.EXE> <gen/na/fntab.c> <record or -> \
                 <xpatch spec out> <asi_ul.h out>

<record> is what runtime/asi.c writes with ASIREC=<file> after the plugin's
DllMain: one changed range of the game's .text per line, "addr len hexbytes".

Each range is either
  code  - it overlaps an instruction of some lifted function: an xpatch 'w'
          site named ul_<addr> (tools/xpatch.py), lifted as a switch;
  data  - a table inside .text (MSVC 7 puts switch tables there): the lifted
          code reads it from guest memory, so the write itself is enough.
asi_ul.h lists every range with its bytes, so the runtime can check that the
plugin wrote exactly what was recorded before it switches anything on.
"""
import sys, os, json, re
sys.path.insert(0, os.path.join(os.path.dirname(__file__), '..'))
from lift import Lifter

meta_p, exe, fntab, rec, spec_out, hdr_out = sys.argv[1:7]
# optional: gen/na/xpatch_data.txt from the engine generation (XPATCH_SOFT):
# recorded ranges that turned out to be data inside .text
data_names = set()
if len(sys.argv) > 7 and os.path.exists(sys.argv[7]):
    data_names = {l.strip() for l in open(sys.argv[7]) if l.strip()}
meta = json.load(open(meta_p))
ranges = []
if rec != '-':
    for ln in open(rec):
        p = ln.split()
        if len(p) == 3: ranges.append((int(p[0], 16), int(p[1]), bytes.fromhex(p[2])))

code = set()
if ranges:
    L = Lifter(exe)
    funcs = [int(x, 16) for x in re.findall(r'0x([0-9a-f]{8})u', open(fntab).read().split('g_fn_ptr')[0])]
    want = set()
    for a, n, _ in ranges: want.update(range(a, a + n))
    lo = min(want); hi = max(want)
    for f in funcs:
        try: blocks, _ = L.discover(f)
        except Exception: continue
        for ins in blocks.values():
            for i in ins:
                if i.address + i.size > lo and i.address <= hi:
                    for b in range(i.address, i.address + i.size):
                        if b in want: code.add(b)

sites = []
with open(spec_out, 'w') as f:
    f.write(f"# xpatch sites recorded from {meta['file']} (sha256 {meta['sha256'][:16]}..) DllMain;\n")
    f.write("# generated by tools/mods/asi_sites.py -- do not edit\n")
    for a, n, b in ranges:
        is_code = any(x in code for x in range(a, a + n))
        name = f"ul_{a:06x}" if is_code else None
        if is_code: f.write(f"w    {name}  {a:x} {b.hex()}\n")
        sites.append((a, n, b, None if name in data_names else name))
with open(hdr_out, 'w') as f:
    f.write("/* generated by tools/mods/asi_sites.py -- do not edit */\n#pragma once\n")
    f.write(f'#define ASI_UL_FILE "{meta["file"]}"\n#define ASI_UL_SHA "{meta["sha256"]}"\n')
    f.write(f'#define ASI_UL_VERSION "sha256 {meta["sha256"][:12]}.., {meta["size"]} bytes"\n')
    f.write(f"#define ASI_UL_BASE 0x{meta['base']:08x}u\n")
    f.write(f"#define ASI_UL_NSITES {len(sites)}\n")
    f.write("static const struct { uint32_t addr, len; const char *bytes; const char *xp; } asi_ul_sites[] = {\n")
    for a, n, b, name in sites:
        esc = ''.join(f'\\x{x:02x}' for x in b)
        f.write(f'  {{0x{a:08x}u, {n}u, "{esc}", {chr(34)+name+chr(34) if name else "0"}}},\n')
    if not sites: f.write('  {0, 0, "", 0},\n')
    f.write("};\n")
nc = sum(1 for s in sites if s[3])
print(f"{len(sites)} ranges: {nc} code sites -> {spec_out}, {len(sites)-nc} data; header {hdr_out}")
