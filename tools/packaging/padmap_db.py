#!/usr/bin/env python3
"""Write runtime/padmap_db.h, the built-in controller mappings of runtime/padmap.c.

Controllers that Apple's GameController framework does not know (DirectInput-mode
pads such as the 8BitDo D-input modes, Logitech "D" mode, generic USB pads) are read
through IOKit HID (runtime/gamepad.m).  Their buttons and axes are numbered the way
SDL's IOKit joystick driver numbers them, so SDL GameControllerDB lines describe
them.  This keeps the macOS IOKit lines of such a list:

  - the GUID's driver byte (byte 14) is 0: an IOKit device, not HIDAPI ('h'),
    GameController ('m'), XInput ('x') or virtual ('v');
  - a platform: field, if any, is "Mac OS X";
  - hint:, platform: and crc: fields are dropped (the runtime is positional, which is
    what SDL3 and the "!SDL_GAMECONTROLLER_USE_BUTTON_LABELS" variants mean).

Input: SDL's src/joystick/SDL_gamepad_db.h (the macOS / IOKit section), a
gamecontrollerdb.txt, or plain mapping lines -- anything with one mapping per line,
quoted or not.  The committed table came from SDL 3.4.14's built-in database
(zlib licence).

  python3 -I tools/packaging/padmap_db.py SOURCE [runtime/padmap_db.h]
"""
import re
import sys

LINE = re.compile(r'"?([0-9a-fA-F]{32}),([^,]*),(.*?)"?,?\s*$')


def keep(line):
    m = LINE.match(line.strip())
    if not m:
        return None
    guid, name, rest = m.group(1).lower(), m.group(2), m.group(3)
    if guid[28:30] != "00":
        return None
    fields = [f for f in rest.split(",") if f]
    plat = [f for f in fields if f.startswith("platform:")]
    if plat and plat[0] != "platform:Mac OS X":
        return None
    fields = [f for f in fields if not f.startswith(("hint:", "platform:", "crc:"))]
    return "%s,%s,%s," % (guid, name, ",".join(fields))


def main():
    if len(sys.argv) < 2:
        print(__doc__)
        return 2
    src = sys.argv[1]
    out = sys.argv[2] if len(sys.argv) > 2 else "runtime/padmap_db.h"
    lines, seen = [], set()
    with open(src, encoding="utf-8", errors="replace") as f:
        for raw in f:
            k = keep(raw)
            if k and k not in seen:
                seen.add(k)
                lines.append(k)
    with open(out, "w", encoding="utf-8") as f:
        f.write("/* Generated by tools/packaging/padmap_db.py -- do not edit.\n"
                " * macOS IOKit controller mappings in SDL GameControllerDB form, from SDL's\n"
                " * built-in gamepad database (zlib licence, https://libsdl.org).\n"
                " * %d entries.  Used by runtime/padmap.c. */\n" % len(lines))
        f.write("static const char *const k_padmap_db[] = {\n")
        for l in lines:
            f.write('    "%s",\n' % l.replace("\\", "\\\\").replace('"', '\\"'))
        f.write("};\n")
    print("%s: %d mappings" % (out, len(lines)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
